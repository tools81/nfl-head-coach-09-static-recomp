"""Assemble config/HC09.toml from the hand-written base and generated fragments.

XenonRecomp has no include mechanism and reads `functions` from [main], so the
fragments are appended after the base (which contains only the [main] table).
"""
import os

CONFIG = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "config")
FRAGMENTS = ["HC09_functions.toml"]

parts = ["# GENERATED by tools/make_config.py -- edit HC09.base.toml instead\n\n",
         open(os.path.join(CONFIG, "HC09.base.toml")).read()]
for name in FRAGMENTS:
    path = os.path.join(CONFIG, name)
    if os.path.exists(path):
        parts.append(f"\n# ---- {name} ----\n" + open(path).read())
open(os.path.join(CONFIG, "HC09.toml"), "w").write("".join(parts))
print("wrote config/HC09.toml")
