"""Generate src/kernel/import_stubs.cpp: a logging stub for every imported kernel/XAM
function that has no hand-written implementation yet.

A function counts as implemented when some file under src/ (other than the generated
file) contains `PPC_FUNC(__imp__Name)`.

Usage: gen_import_stubs.py <imports.csv>
"""
import csv
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "src")
OUT = os.path.join(SRC, "kernel", "import_stubs.cpp")


def implemented():
    names = set()
    for dirpath, _, files in os.walk(SRC):
        for f in files:
            path = os.path.join(dirpath, f)
            if f.endswith((".cpp", ".h")) and os.path.abspath(path) != os.path.abspath(OUT):
                text = open(path, encoding="utf-8").read()
                names |= set(re.findall(r"PPC_FUNC\(__imp__(\w+)\)", text))
                # NetDll exports defined through helper macros (xam_net.cpp)
                names |= {"NetDll_" + n for n in re.findall(r"^HC09_(?:SOCKET|XNET)_FAILURE\((\w+)\)", text, re.M)}
    return names


def main(csv_path):
    done = implemented()
    rows = sorted({(r["library"], r["name"]) for r in csv.DictReader(open(csv_path))
                   if r["kind"] == "thunk"}, key=lambda r: r[1])
    lines = [
        "// GENERATED by tools/gen_import_stubs.py -- do not edit.",
        "// Unimplemented kernel/XAM imports: log the first call and return 0 in r3.",
        '#include "kernel/stub.h"',
        "",
    ]
    stubbed = 0
    for lib, name in rows:
        if name in done:
            continue
        lines.append(f'HC09_IMPORT_STUB({name}, "{lib}")')
        stubbed += 1
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"{stubbed} stubs, {len(done)} implemented")
    write_slots(csv_path)


def write_slots(csv_path):
    """Emit src/kernel/import_slots.inc: every import-table slot and what it must hold.

    Function imports have a data slot (the IAT entry the original thunk loaded from) and a
    thunk; the slot gets the thunk address. Data-only imports get a host-provided object.
    """
    records = list(csv.DictReader(open(csv_path)))
    thunks = {(r["library"], r["ordinal"]): r["address"] for r in records if r["kind"] == "thunk"}
    lines = ["// GENERATED by tools/gen_import_stubs.py -- do not edit."]
    for r in records:
        if r["kind"] != "variable":
            continue
        thunk = thunks.get((r["library"], r["ordinal"]))
        if thunk:
            lines.append(f"HC09_FUNCTION_SLOT({r['address']}, {thunk})  // {r['name']}")
        else:
            lines.append(f"HC09_VARIABLE_SLOT({r['name']}, {r['address']})")
    open(os.path.join(SRC, "kernel", "import_slots.inc"), "w", encoding="utf-8").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
